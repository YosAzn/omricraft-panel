// Text direction for a language code (defaults to ltr for unknown codes).
export const dirForLang = (lang) =>
  (LANGUAGES.find(l => l.code === lang)?.dir) || 'ltr';

// Resolve a UI string with graceful fallback: current lang -> en -> he -> key.
// Use this instead of reading DICT[lang][key] directly so the 8 partial
// languages never show blank text.
export const translate = (lang, key) =>
  DICT[lang]?.[key] ?? DICT.en?.[key] ?? DICT.he?.[key] ?? key;
