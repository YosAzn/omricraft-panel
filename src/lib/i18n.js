// Ordered list of every supported language: code, native label, text direction.
// dir is 'rtl' for Hebrew & Arabic, 'ltr' for everyone else.
export const LANGUAGES = [
  { code: 'he', label: 'עברית',     dir: 'rtl' },
  { code: 'en', label: 'English',   dir: 'ltr' },
  { code: 'ru', label: 'Русский',   dir: 'ltr' },
  { code: 'fr', label: 'Français',  dir: 'ltr' },
  { code: 'it', label: 'Italiano',  dir: 'ltr' },
  { code: 'es', label: 'Español',   dir: 'ltr' },
  { code: 'de', label: 'Deutsch',   dir: 'ltr' },
  { code: 'pt', label: 'Português', dir: 'ltr' },
  { code: 'ar', label: 'العربية',   dir: 'rtl' },
  { code: 'pl', label: 'Polski',    dir: 'ltr' }
];

// Text direction for a language code (defaults to ltr for unknown codes).
export const dirForLang = (lang) =>
  (LANGUAGES.find(l => l.code === lang)?.dir) || 'ltr';

// Resolve a UI string with graceful fallback: current lang -> en -> he -> key.
// Use this instead of reading DICT[lang][key] directly so the 8 partial
// languages never show blank text.
export const translate = (lang, key) =>
  DICT[lang]?.[key] ?? DICT.en?.[key] ?? DICT.he?.[key] ?? key;
